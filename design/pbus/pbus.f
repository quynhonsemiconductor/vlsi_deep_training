# =============================================================================
# Filelist for the pbus block (P_BUS, QNSC_PBUS_MAS).
#
# This is the single place that says which files build this block, and in what
# order. CI lints the block through this file, so a file not listed here is not
# compiled and not checked.
#
# Rules:
#   - Upstream IP is LISTED here, never copied into rtl/. Paths are relative to
#     this file, so they start with ../../vendor/... or ../../util/gen/...
#   - Order matters. Packages and `define files first, then leaf modules, then
#     the modules that instantiate them, then our wrapper last.
#   - Anything under rtl/ is code written here. Anything under ../../util/gen/
#     is generated by a recipe there and never edited by hand.
#
# The core is generated by APB-BUS-Generator (vendor/nguyenquanicd/
# APB-BUS-Generator) from util/gen/p_bus/p_bus.xlsx; `make gen IP=p_bus`
# regenerates it, `make gen-check` (CI) checks the committed files are a
# regeneration. One master, so no round-robin cell (ArbRRBalance) is compiled.
# =============================================================================

